"""Browser acceptance against Bas.Integration --serve, isolated fake engine over real HTTPS."""
import json
import sys
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

url = sys.argv[1] if len(sys.argv) > 1 else 'http://localhost:39761/bas.html'
output = Path('.runtime/bas-browser'); output.mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch()
    page = browser.new_page(viewport={'width': 1360, 'height': 950})
    errors = []; page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(url)
    expect(page.locator('.project')).to_have_count(1)
    page.locator('.project').click()
    expect(page.locator('#engineState')).to_contain_text('ready')
    expect(page.locator('#projectPath')).to_be_disabled()
    expect(page.locator('#delete')).to_be_enabled()
    expect(page.locator('#log')).to_contain_text('<img src=x')
    assert page.locator('#log img').count() == 0
    page.locator('#unload').click(); expect(page.locator('#projectPath')).to_be_enabled()
    expect(page.locator('#log')).to_have_text('')
    xml_path = page.locator('#projectPath').input_value()
    page.locator('#new').click()
    page.route('**/tasker/pick?*', lambda route: route.fulfill(json={'ok': True, 'path': ''}), times=1)
    with page.expect_response('**/tasker/pick?*'):
        page.locator('#pickProject').click()
    expect(page.locator('#pickProject')).to_be_enabled()
    expect(page.locator('#projectPath')).to_have_value('')
    def choose_xml(route):
        assert 'mode=file' in route.request.url and 'ext=bas' in route.request.url
        route.fulfill(json={'ok': True, 'path': xml_path})
    page.route('**/tasker/pick?*', choose_xml, times=1)
    page.locator('#pickProject').click()
    expect(page.locator('#projectPath')).to_have_value(xml_path)
    expect(page.locator('#name')).to_have_value('test')
    expect(page.locator('[data-resource="X"]')).to_have_value('2')
    page.locator('.project').click()
    expect(page.locator('[data-resource="X"]')).to_have_value('2')
    expect(page.locator('[data-resource="Y"]')).to_have_value('3')
    page.locator('[data-resource="X"]').fill('9')
    page.locator('.resource-field').filter(has=page.locator('[data-resource="X"]')).get_by_role('button', name='Use XML default').click()
    expect(page.locator('[data-resource="X"]')).to_have_value('2')
    assert json.loads(page.locator('#parameters').input_value()) == {'Y': 3}
    page.locator('[data-resource="X"]').fill('3')
    page.locator('[data-resource="Y"]').fill('4')
    assert json.loads(page.locator('#parameters').input_value()) == {'X': 3, 'Y': 4}
    page.locator('#save').click(); expect(page.locator('#save')).to_be_enabled()
    page.reload(); expect(page.locator('.project')).to_have_count(1); page.locator('.project').click()
    expect(page.locator('[data-resource="X"]')).to_have_value('3')
    expect(page.locator('[data-resource="Y"]')).to_have_value('4')
    page.locator('#resourceJson summary').click()
    page.locator('#parameters').fill('{"X":8,"Y":4}')
    page.locator('#parameters').dispatch_event('change')
    expect(page.locator('[data-resource="X"]')).to_have_value('8')
    page.locator('[data-resource="X"]').fill('3')
    page.locator('#save').click(); expect(page.locator('#save')).to_be_enabled()
    page.locator('#run').click()
    expect(page.locator('#runs td.succeeded')).to_have_count(1, timeout=15000)
    expect(page.locator('#runs .result')).to_have_text('7')
    def lost_reply(route):
        route.fetch(); route.abort('failed')
    page.route('**/bridge-local/bas/projects/*/run', lost_reply, times=1)
    page.locator('#run').click(); expect(page.locator('#recover')).to_be_enabled()
    expect(page.locator('#run')).to_be_disabled()
    page.locator('#recover').click(); expect(page.locator('#recover')).to_be_hidden()
    expect(page.locator('#runs tr')).to_have_count(2)
    expect(page.locator('#run')).to_be_enabled(timeout=15000)
    page.route('**/bridge-local/bas/projects/*/run', lambda route: route.abort('failed'), times=1)
    page.locator('#run').click(); expect(page.locator('#recover')).to_be_enabled()
    page.locator('#recover').click(); expect(page.locator('#dismiss')).to_be_visible()
    page.locator('#dismiss').click(); expect(page.locator('#recover')).to_be_hidden()
    expect(page.locator('#run')).to_be_enabled()
    expect(page.locator('#runs tr')).to_have_count(2)
    page.locator('#node').select_option(index=1)
    expect(page.locator('.project')).to_have_count(1); page.locator('.project').click()
    expect(page.locator('[data-resource="Y"]')).to_have_value('4')
    remote_node = page.locator('#node').input_value()
    page.evaluate('([node, folder]) => localStorage.setItem("bridge-folder:" + node, folder)', [remote_node, str(Path(xml_path).parent)])
    page.locator('#new').click(); page.locator('#pickProject').click()
    expect(page.locator('.br-file-dialog')).to_be_visible()
    expect(page.locator('.br-file-entry').filter(has_text='test.xml')).to_be_visible()
    assert page.locator('.br-file-entry').filter(has_text='source.xml').count() == 1
    assert page.locator('.br-file-entry').filter(has_text='bas-projects.bin').count() == 0
    page.locator('.br-file-entry').filter(has_text='test.xml').click()
    expect(page.locator('.br-file-dialog')).to_have_count(0)
    expect(page.locator('#projectPath')).to_have_value(xml_path)
    expect(page.locator('[data-resource="X"]')).to_have_value('2')
    page.locator('.project').click()
    expect(page.locator('#runs tr')).to_have_count(2)
    page.locator('#run').click(); expect(page.locator('#stop')).to_be_enabled()
    expect(page.locator('#delete')).to_be_disabled()
    page.locator('#stop').click(); expect(page.locator('#runs')).to_contain_text('stopped')
    expect(page.locator('#run')).to_be_enabled()
    expect(page.locator('#delete')).to_be_enabled()
    page.route('**/api/bas/projects/*/unload', lost_reply, times=1)
    page.locator('#unload').click(); expect(page.locator('#recover')).to_be_enabled()
    page.locator('#recover').click(); expect(page.locator('#recover')).to_be_hidden()
    expect(page.locator('#log')).to_have_text('')
    page.locator('#run').click(); expect(page.locator('#log')).to_contain_text('fixture log')
    expect(page.locator('#runs td.succeeded')).to_have_count(1, timeout=15000)
    delayed_resources = []
    page.route('**/api/bas/resources?*', lambda route: delayed_resources.append(route), times=1)
    page.locator('#loadResources').click()
    expect(page.locator('#resourceStatus')).to_contain_text('Reading XML')
    page.locator('#new').click()
    assert len(delayed_resources) == 1
    delayed_resources[0].fulfill(json={'engineVersion': '31.1.0', 'resources': [
        {'name': 'STALE', 'type': 'FixedString', 'defaultValue': 'old', 'editable': True, 'min': None, 'max': None}]})
    expect(page.locator('#resourceStatus')).to_contain_text('Select an XML')
    expect(page.locator('[data-resource]')).to_have_count(0)
    page.locator('.project').click()
    expect(page.locator('[data-resource="X"]')).to_have_value('3')
    for theme in ('graphite', 'graphite-light'):
        page.evaluate('theme => document.documentElement.dataset.theme = theme', theme)
        page.screenshot(path=str(output / f'bas-{theme}.png'), full_page=True)
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    saved = page.evaluate("localStorage.getItem('bas-node')")
    loading = browser.new_page()
    loading.add_init_script("localStorage.setItem('bas-node', " + json.dumps(saved) + ")")
    held = []; requested = []
    loading.route('**/bridge-local/connections', lambda route: held.append(route))
    loading.on('request', lambda request: requested.append(request.url))
    loading.goto(url, wait_until='domcontentloaded'); loading.wait_for_timeout(2500)
    assert not any('/bas/projects' in request for request in requested)
    held[0].continue_()
    expect(loading.locator('#node')).to_have_value(saved)
    expect(loading.locator('.project')).to_have_count(1)
    loading.close()
    expect(page.locator('#delete')).to_be_enabled()
    delete_requests = []
    page.on('request', lambda request: delete_requests.append((request.method, request.url)))
    page.locator('#delete').click()
    expect(page.locator('.project')).to_have_count(0)
    assert len([r for r in delete_requests if r[0] == 'DELETE']) == 1
    assert not any(r[1].endswith('/unload') for r in delete_requests)
    assert Path(xml_path).is_file()
    assert not errors, errors
    browser.close()
    print('PASS XML page: local/remote HTTPS, resource edit, run/stop, safe logs, mutation recovery, unload cursor reset, saved-node isolation, two themes, stopped loaded project deletion without Release runtime')
