import json
import time
import os
from pathlib import Path
from playwright.sync_api import sync_playwright

workspace=Path('.superpowers/sdd/2026-10-15-tasker-remote-bridge')
fixture=json.loads(Path(os.environ.get('BRIDGE_FIXTURE_PATH',str(workspace/'fixture.json'))).read_text())
with sync_playwright() as p:
    edge=Path('C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe')
    browser=p.chromium.launch(headless=True,executable_path=str(edge) if edge.exists() else None)
    page=browser.new_page(viewport={'width':1500,'height':1000})
    errors=[]
    page.on('pageerror',lambda error: errors.append(str(error)))
    page.goto(fixture['local_url']+'/?page=tasker')
    page.wait_for_function("typeof schedules!=='undefined' && schedules.some(s=>s.id==='local-only')")
    page.wait_for_function("document.querySelector('#bridgeNode').options.length>1")
    page.select_option('#bridgeNode',fixture['connection_id'])
    page.wait_for_function("schedules.length>0 && !schedules.some(s=>s.id==='local-only')")
    task=page.evaluate("schedules[0].id")
    page.evaluate("id=>selectRow(id,false,'settings')",task)
    page.wait_for_selector('#f_name')
    name='REMOTE BROWSER EDIT '+str(int(time.time()))
    page.locator('#f_name').fill(name)
    page.locator('#f_name').blur()
    page.evaluate("saveSchedule(selectedId)")
    print(page.evaluate("({dirty:formDirty, names:schedules.map(x=>x.name), message:document.querySelector('#dialogMsg').textContent,status:document.querySelector('#bridgeStatus').textContent})"),flush=True)
    page.screenshot(path=str(workspace/'save-debug.png'),full_page=True)
    page.wait_for_function("name=>!formDirty && schedules.some(s=>s.name===name)",arg=name)
    assert page.locator('#bridgeStatus').inner_text().startswith('Connected')
    page.locator('[data-tab="settings"]').click()
    page.wait_for_selector('#f_script_path')
    page.evaluate("pickPath('file')")
    page.wait_for_selector('.br-file-dialog')
    page.locator('.br-file-toolbar input').fill(fixture['root'])
    page.locator('[data-go]').click()
    page.locator('[data-new]').click()
    page.wait_for_selector('#dialogInput',state='visible')
    folder='browser-folder-'+str(int(time.time()))
    page.locator('#dialogInput').fill(folder)
    page.locator('#dialogButtons button').filter(has_text='Create').click()
    page.wait_for_function("name=>document.querySelector('.br-file-toolbar input').value.endsWith(name)",arg=folder)
    page.locator('[data-up]').click()
    page.get_by_role('button',name='test.py',exact=False).click()
    page.wait_for_selector('.br-file-dialog',state='detached')
    assert page.locator('#f_script_path').input_value().endswith('test.py')
    page.screenshot(path=str(workspace/'tasker-remote.png'),full_page=True)
    page.evaluate("document.documentElement.dataset.theme='graphite-light'")
    page.screenshot(path=str(workspace/'tasker-remote-light.png'),full_page=True)
    page.goto(fixture['local_url']+'/?page=config')
    page.locator('[data-sec="remote-tasker"].cfg-rail-item').click()
    page.wait_for_function("document.querySelector('#brConnections').textContent.includes('Server')")
    assert 'secret' not in page.locator('#brConnections').inner_text().lower()
    page.screenshot(path=str(workspace/'bridge-config.png'),full_page=True)
    browser.close()
    print(json.dumps({'browser':'PASS','errors':errors},ensure_ascii=False))
    assert not errors,errors
